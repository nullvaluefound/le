#!/usr/bin/env python3
"""Generate self-contained native manual installers from shared source pieces."""
from pathlib import Path
import json
import re
import shlex

root = Path(__file__).resolve().parents[1]
for action in ('install', 'uninstall'):
    common = (root / 'packaging/linux/common.sh').read_text(encoding='utf-8')
    body = (root / f'packaging/linux/{action}.body.sh').read_text(encoding='utf-8')
    target = root / f'{action}.sh'
    target.write_text('#!/usr/bin/env bash\n# Generated by packaging/generate_manual.py; edit packaging/linux sources.\n' + common + '\n' + body, encoding='utf-8', newline='\n')
    target.chmod(0o755)
    windows = root / f'packaging/windows/{action}.body.ps1'
    if windows.exists():
        parameters, content = windows.read_text(encoding='utf-8').split('# COMMON\n', 1)
        shared = (root / 'packaging/windows/common.ps1').read_text(encoding='utf-8')
        (root / f'{action}.ps1').write_text(parameters + shared + '\n' + content, encoding='utf-8-sig', newline='\r\n')
        (root / f'{action}.bat').write_text('@echo off\r\npowershell.exe -NoLogo -NoProfile -ExecutionPolicy Bypass -File "%~dp0' + action + '.ps1" %*\r\nexit /b %errorlevel%\r\n', encoding='ascii', newline='')

# The APT installer embeds the existing tested trust bootstrap. A downloaded
# copy needs no sibling scripts, Python, or manually supplied fingerprint.
data = json.loads((root / 'packaging/distribution.json').read_text(encoding='utf-8'))
fingerprint = data.get('apt_signing_fingerprint') or ''
architectures = data.get('architectures', [])
if not isinstance(fingerprint, str) or (fingerprint and not re.fullmatch(r'[A-F0-9]{40,64}', fingerprint)):
    raise ValueError('Use the full production APT signing fingerprint')
if not architectures or not set(architectures).issubset({'amd64', 'arm64'}):
    raise ValueError('Configure only published package architectures')
settings = {
    'LE_INSTALL_APT_URL': data['apt_base_url'],
    'LE_INSTALL_APT_SUITE': data['apt_suite'],
    'LE_INSTALL_APT_FINGERPRINT': fingerprint,
    'LE_INSTALL_APT_ARCHITECTURES': ' '.join(architectures),
}
header = '#!/usr/bin/env bash\n# Generated by packaging/generate_manual.py; do not edit this copy.\nset -euo pipefail\n'
header += ''.join(f'{name}={shlex.quote(value)}\n' for name, value in settings.items())
bootstrap = (root / 'packaging/setup-apt.sh').read_text(encoding='utf-8')
entrypoint = (root / 'packaging/linux/install-apt.body.sh').read_text(encoding='utf-8')
installer = root / 'install-apt.sh'
installer.write_text(header + '\nle_configure_apt_repository() (\n' + bootstrap + '\n)\n\n' + entrypoint, encoding='utf-8', newline='\n')
installer.chmod(0o755)
